import { useEffect, useState } from "react"
import { cn } from "@/lib/utils"
import { Link } from "@tanstack/react-router"
import { BrandLink } from "@/components/brand/ButtonLink"
import { authClient } from "@/lib/auth-client"

/**
 * `to`: a page of its own, opened through the router (no page reload).
 * `href` only: a section of the home page (`/#how`); a plain link, so the
 * browser loads the home page when needed and scrolls to the section.
 */
type NavItem = { href: string; label: string; to?: "/templates" | "/blog" }

// Absolute paths so the same nav works on every page, not just "/".
export const NAV_LINKS: ReadonlyArray<NavItem> = [
  { href: "/#how", label: "How it works" },
  { href: "/#features", label: "Features" },
  { href: "/templates", label: "Templates", to: "/templates" },
  { href: "/blog", label: "Blog", to: "/blog" },
]

/** One marketing nav entry (header and footer). */
export function NavLink({ link }: { link: NavItem }) {
  return link.to ? (
    <Link to={link.to} className="link">
      {link.label}
    </Link>
  ) : (
    <a href={link.href} className="link">
      {link.label}
    </a>
  )
}

export function Nav() {
  const [scrolled, setScrolled] = useState(false)
  // Client-side: marketing pages stay static and never wait on the database.
  // Until it resolves (and on the server) the signed-out links show.
  const { data: session } = authClient.useSession()

  useEffect(() => {
    const onScroll = () => setScrolled(window.scrollY > 24)
    onScroll()
    window.addEventListener("scroll", onScroll, { passive: true })
    return () => window.removeEventListener("scroll", onScroll)
  }, [])

  return (
    <header
      className={cn(
        "fixed inset-x-0 top-0 z-50 transition-all duration-500",
        scrolled
          ? "border-b border-gold/10 bg-ink/75 py-3 backdrop-blur-xl"
          : "py-6"
      )}
    >
      <nav className="mx-auto flex max-w-6xl items-center justify-between px-4 sm:px-6">
        <Logo />
        <ul className="hidden items-center gap-8 md:flex">
          {NAV_LINKS.map((link) => (
            <li key={link.href}>
              <NavLink link={link} />
            </li>
          ))}
        </ul>
        <div className="flex items-center gap-5">
          {session ? (
            <BrandLink to="/dashboard" variant="outline" size="md">
              My invitations
            </BrandLink>
          ) : (
            <>
              <Link to="/sign-in" className="hidden link sm:inline">
                Sign in
              </Link>
              <BrandLink to="/templates" variant="outline" size="md">
                Get started
              </BrandLink>
            </>
          )}
        </div>
      </nav>
    </header>
  )
}

/**
 * The logo, linking home through the router, so the app stays loaded and
 * only the page content changes. Signed-in pages (dashboard, editor) pass
 * `href="/dashboard"`: their home is the invitation list, and the marketing
 * page would show its signed-out header for a moment. The editor saves
 * pending edits before it lets go (see `Editor.tsx`).
 */
export function Logo({ href = "/" }: { href?: "/" | "/dashboard" }) {
  return (
    <Link to={href} className="flex items-center">
      {/* Mark + wordmark, generated by `pnpm brand:icons`. */}
      <img
        src="/logo.svg"
        alt="Alikeni"
        width={98}
        height={32}
        className="h-8 w-auto"
      />
    </Link>
  )
}
